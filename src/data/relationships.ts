/**
 * 관계 시스템 데이터(순수 선언).
 * 계열별 캐릭터와 호감도를 쌓아 3단계 만남 arc(웹소설)를 진행하고, 완주하면 선물을 받는다.
 * 로직은 systems/relationship.ts가, 화면은 ui가 담당한다(data는 규칙에 비의존).
 */

/**
 * 만남 이벤트 한 편(arc 1편).
 * - pages: 웹소설 본문 페이지들. `{name}` 토큰은 상대 이름으로 치환된다(ui).
 * - choices: 기존 이벤트와 동일한 EventChoice(effect·result). 효과 적용은 systems/events.applyEffect.
 *   ⚠️ Arc2(events[1])에만 "친구/연인" 2선택지를 둔다 — 인덱스 0=friend, 1=lover로 bond가 확정된다.
 *   (서사·문구만 분기, 보상·effect는 동일하게 맞춘다.) Arc1·3은 공용 선택지.
 */
export interface MeetEvent {
  pages: string[];
  choices: EventChoice[];
}

/**
 * 관계 캐릭터 한 명.
 * - attribute + likedKind가 게시 트윗의 attr + kind와 일치하면 호감도가 오른다.
 * - events: [Arc1, Arc2, Arc3]. affinity 임계 30/60/90에서 차례로 열린다.
 * - giftId: Arc3 완주 시 ownedItems에 들어갈 선물 id. 반드시 REL_GIFTS에 정의돼 있어야 한다
 *   (없으면 서랍장에서 조용히 소실 — resolveItem 함정).
 */
export interface RelationshipChar {
  id: string;
  name: string;
  gender: "m" | "f";
  attribute: AttributeId;
  likedKind: TweetKind;
  events: [MeetEvent, MeetEvent, MeetEvent];
  giftId: string;
}

/**
 * 관계 완주 선물(전용 아이템).
 * shop의 resolveItem이 이 목록을 훑어 서랍장·판매에서 해석한다(systems/shop.ts에 등록됨).
 * ⚠️ id는 다른 아이템 출처와 겹치지 않게 `rel_gift_` 프리픽스를 쓴다(ITEM_INDEX 충돌 방지).
 * price는 **정가** — 판매 시 기존 아이템과 동일하게 50%가 지급되고, 관계 선물은 추가로
 * 평판/도덕 페널티가 붙는다(정을 판 대가). 선물엔 스탯 부스트가 없다.
 */
export interface RelGift {
  id: string;
  name: string;
  /** 정가(판매 시 50% 지급) */
  price: number;
  desc?: string;
}

