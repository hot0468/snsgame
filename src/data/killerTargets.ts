export function targetById(id: string): KillerTarget | undefined {
  return KILLER_TARGETS.find((t) => t.id === id);
}

/**
 * 타겟 프로필에 표시할 30개 트윗 — 고유 트윗(정답 포함)을 공용 필러 사이에 결정론적으로 흩는다.
 * 같은 타겟은 언제 봐도 같은 순서(핸들 해시 시드) — 재렌더에도 흔들리지 않는다.
 */
export function targetFullTweets(target: KillerTarget): string[] {
  const need = Math.max(0, TARGET_TWEET_COUNT - target.tweets.length);
  const h = hashInt(target.id);
  const filler: string[] = [];
  for (let i = 0; i < need; i++) {
    filler.push(KILLER_FILLER_TWEETS[(h + i * 7) % KILLER_FILLER_TWEETS.length]);
  }
  // 고유 트윗(정답 포함)을 결정론적 위치에 끼워 넣어 정답을 피드 속에 묻는다.
  const out = [...filler];
  target.tweets.forEach((t, i) => {
    const pos = (h + (i + 1) * 13) % (out.length + 1);
    out.splice(pos, 0, t);
  });
  return out;
}

/** 핸들(@ 제외)로 타겟을 찾는다(프로필 조회용). */
export function targetByHandle(handle: string): KillerTarget | undefined {
  const h = handle.replace(/^@/, "");
  return KILLER_TARGETS.find((t) => t.handle === h);
}
