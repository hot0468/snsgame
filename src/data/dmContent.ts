/**
 * 이어지는 대화의 '화제'.
 *
 * ⚠️ 이게 없으면 대화가 반드시 어긋난다. 짝(me→partner)만으로는 **직전 상대 말 → 내 말**이
 *    맞물리지 않기 때문이다. 상대의 답장은 내 말에 대한 리액션이라 새로 던진 내용이 없는데,
 *    followup 대사들은 "상대가 방금 뭔가 말했다"를 전제로 쓰여 있어서
 *    "여쭤볼게요 ㅋㅋ" → "듣고 보니 그러네요, 생각 못 했어요!" 같은 대화가 나왔다.
 *
 * 그래서 상대는 리액션 끝에 `prompt`로 **화제를 던지고**, 내 선택지는 그 화제에 대한
 * 대답(`replies`)에서만 나온다. 대화가 "던지고 받는" 구조가 되어야 말이 된다.
 *
 * ★문맥 중립 원칙은 여기서도 유지한다 — 계정 주제(포카/레시피 등)를 단정하지 않는다.
 */
