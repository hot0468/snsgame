/** id로 관계 캐릭터 조회 */
export function getRelChar(id: string): RelationshipChar | undefined {
  return RELATIONSHIP_CHARS.find((c) => c.id === id);
}

/** 해당 계열(attribute)에 속한 관계 캐릭터 목록 */
export function charsForAttribute(attr: AttributeId): RelationshipChar[] {
  return RELATIONSHIP_CHARS.filter((c) => c.attribute === attr);
}

/** id로 관계 선물 조회 */
export function getRelGift(id: string): RelGift | undefined {
  return REL_GIFTS.find((g) => g.id === id);
}
