/**
 * 성인 트윗 누적이 임계치를 넘으면 AV배우 제의 DM을 1회 스폰한다.
 * tweetSystem.ts의 isAdult 블록에서 성인 트윗마다 호출된다(내부 가드로 1회만 동작).
 * @returns 스폰되면 true
 */
export function maybeSpawnAvOfferDM(state: GameState): boolean {
  if (state.avOffered || state.avJob) return false;
  if (!state.adultMode) return false;
  if (state.adultTweetsPosted < AV_OFFER_ADULT_TWEETS) return false;
  const account = getActiveAccount(state);
  const npc = makeRandomAccount(true, state.day);
  account.dms.unshift({
    id: uid("dm"),
    partnerName: npc.name,
    partnerHandle: npc.handle,
    attribute: npc.attribute,
    isAdult: true,
    messages: [
      { id: uid("dmm"), from: "partner", text: pick(AV_OFFER_OPENERS), day: state.day },
    ],
    unread: true,
    metOffline: false,
    wantsToMeet: false,
    avOffer: true,
  });
  state.avOffered = true;
  return true;
}

/**
 * AV배우 제의를 수락 → 계약 생성. 익월부터 근무·정산. 해당 DM 제의 플래그 해제.
 * ⚠️ **기존 직업(회사/AV)이 있으면 아무것도 하지 않는다** — UI가 전환 여부를 물어
 *    switchToAvJob을 호출한다(직업 배타).
 */
export function acceptAvJob(state: GameState, threadId: string): void {
  if (hasAnyJob(state)) return;
  state.avJob = {
    joinedDay: state.day,
    workDaysThisMonth: 0,
    totalWorkDays: 0,
    lastWorkDay: -1,
    condomlessThisMonth: 0,
    lastSalaryMonth: -1,
    stdUntilDay: -1,
  };
  const thread = getActiveAccount(state).dms.find((t) => t.id === threadId);
  if (thread) thread.avOffer = false;
  markJobExperienced(state, JOB_ID.av); // 직업 도감 해금(계약 해지해도 남는다)
  addSchedule(state, "AV배우 계약", "system");
}

/** 기존 직업을 그만두고 AV 계약으로 갈아탄다(UI 전환 확정 시). */
export function switchToAvJob(state: GameState, threadId: string): void {
  quitCurrentJob(state);
  acceptAvJob(state, threadId);
}

/** AV배우 제의를 거절 → 제의 플래그만 해제(재제의 없음). */
export function declineAvJob(state: GameState, threadId: string): void {
  const thread = getActiveAccount(state).dms.find((t) => t.id === threadId);
  if (thread) thread.avOffer = false;
}

/**
 * 지금 AV 촬영 업무가 가능한지.
 * 계약 후 익일부터, 심야 슬롯, 행동력 충분, 하루 1회(lastWorkDay 가드).
 */
export function canWorkAvNow(state: GameState): boolean {
  const job = state.avJob;
  if (!job) return false;
  return (
    state.slot === LATE_SLOT &&
    state.day >= firstAvWorkDay(job.joinedDay) &&
    state.day > job.stdUntilDay && // 성병 회복 전엔 촬영 불가
    state.resources.action >= AV_WORK_ACTION_COST &&
    job.lastWorkDay !== state.day
  );
}

/**
 * 첫 근무일 = 계약 후 처음 오는 26일. 근무·정산 사이클이 26일에 앵커된다
 * (월급은 25일 지급, 근무일·노콘은 그 다음날 26일에 리셋 → 26~25가 한 '달').
 */
export function firstAvWorkDay(joinedDay: number): number {
  let d = joinedDay + 1;
  while (dateOfMonth(d) !== 26) d++;
  return d;
}

/** 이번 촬영에서 노콘 제안이 뜨는지(상태 변경 없음 — UI가 먼저 물어본다). */
export function rollCondomlessOffer(_state: GameState): boolean {
  return chance(AV_CONDOMLESS_CHANCE);
}

/**
 * 표시·지급용 이번 달 AV 월급 = **이번 달 근무일 × 일당** + 노콘 누적 가산.
 * maybeAvPayday(economy.ts)와 UI 직업란이 동일 공식을 쓴다(표시=실지급).
 * 안 나가면 0원이다 — 반감 규칙은 없앴다(무노동 무임금).
 */
export function avSalaryOf(state: GameState): number {
  const job = state.avJob;
  if (!job) return 0;
  return job.workDaysThisMonth * AV_PAY_PER_DAY + job.condomlessThisMonth * AV_CONDOMLESS_BONUS;
}

