/**
 * 기부 — 돈을 **도덕성**으로 바꾸는 유일한 창구.
 *
 * 왜 넣었나: 후반에 돈이 고인다. 승급 축하금·시상식 상금·협찬이 붙으면서 수입은 늘었는데
 * 주거 최고 단계와 상점을 다 사고 나면 쓸 곳이 없다. 큰돈이 의미를 잃는 자리를 메운다.
 *
 * 규칙(금액 제한·효과·쿨다운)은 `systems/donation.ts`가 소유한다.
 *
 * ⚠️ **평판은 안 준다**(사용자 확정). 횟수 제한이 없어서 평판까지 주면 현금으로 무한히
 *    살 수 있는데, 평판은 도달 배율 3.3배가 걸린 축이라 트윗·논란 관리가 통째로 무의미해진다.
 *    도덕성은 깎이는 지점이 400곳인데 올리는 창구가 여기뿐이라 그쪽만 연다.
 *
 * ⚠️ **세 단체는 금액 구간으로 갈린다.** 평판이 빠지면서 성격 차이가 사라졌기 때문이다 —
 *    그냥 두면 1점당 제일 싼 하나만 남고 나머지는 죽는다. 지금은 소액(밥집)·중간(보호소)·
 *    거액(장학회) 순으로 **클수록 1점당 값이 조금씩 싸다**. 후반에 고이는 돈의 출구가
 *    이 축의 목적이라 큰 쪽에 이점을 준다.
 *
 * ⚠️ 단체는 전부 패러디다(CLAUDE.md 작명 규약).
 */

export interface DonationTarget {
  id: string;
  name: string;
  /** 한 줄 소개 */
  desc: string;
  emoji: string;
  /** 최소 기부액(원) */
  minAmount: number;
  /**
   * 이 금액마다 효과 1단계. 액수가 커도 `maxSteps`에서 멈춘다.
   * ⚠️ 이 값을 낮추거나 maxSteps를 키우면 "돈으로 평판 사기"가 열린다 — 파일 상단 경고 참조.
   */
  perStep: number;
  /** 효과 단계 상한 */
  maxSteps: number;
  /**
   * 1단계당 도덕성 상승.
   *
   * ⚠️ 평판보다 후하게 잡혀 있다(사용자 확정). 게임 안에 **도덕성이 깎이는 지점이 400곳**인데
   *    올리는 창구는 사실상 여기뿐이라, 평판과 같은 비중으로 두면 한 번 바닥친 도덕성을
   *    되돌릴 방법이 없다. 평판은 트윗·논란 관리로도 오르지만 도덕성은 그렇지 않다.
   */
  moralityPerStep: number;
  /** 기부 후 문구 */
  thanks: string;
}

