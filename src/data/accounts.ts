/**
 * 남의 트윗 한 개 생성.
 * `lines`가 오면 그 전용 문구 풀만 쓴다(고정 캐릭터 계정 — 행사 트윗·난독화 제외).
 */
function makeForeignTweet(
  attr: AttributeId,
  author: { name: string; handle: string },
  adultMode: boolean,
  day: number,
  lines?: string[],
): Tweet {
  // 아이돌/애니/배우 트윗은 가끔 행사 안내 트윗으로 뜬다(참여하기 대상)
  const ev = lines ? undefined : maybeEventTweet(attr, day);
  const isAdult = !ev && !lines && (ATTRIBUTES[attr].adultOnly || (adultMode && chance(0.2)));
  const text = ev ? ev.text : pick(lines ?? allTemplatesFor(attr, adultMode));
  const tweet: Tweet = {
    id: uid("ftweet"),
    authorName: author.name,
    authorHandle: author.handle,
    attribute: attr,
    isAdult,
    text,
    createdDay: day,
    likes: randInt(0, 500),
    retweets: randInt(0, 120),
    gainedFollowers: 0,
    event: ev?.event,
  };
  // 미디어 세트 트윗이면 그 미디어를, 아니면 확률적으로 랜덤 미디어 첨부
  const mset = mediaSetFor(text);
  if (mset) tweet.media = mset.media;
  else if (!ev && chance(0.35)) tweet.media = makeMedia(attr);
  // 일부 트윗은 난도가 높아, 어휘력이 낮으면 글자가 깨져 보인다(행사·캐릭터 트윗 제외).
  if (lines) return tweet;
  // 난이도는 어휘력과 같은 0~999 스킬 스케일이다(구 25~95 → 250~950).
  if (!ev && chance(0.4)) tweet.difficulty = randInt(250, 950);
  return tweet;
}

/**
 * 탐색용 랜덤 계정 하나 생성.
 * adultMode가 꺼져 있으면 성인계 계정/트윗은 제외한다.
 */
export function makeRandomAccount(adultMode: boolean, day: number): Account {
  const pool = adultMode
    ? ALL_ATTRIBUTE_IDS
    : ALL_ATTRIBUTE_IDS.filter((a) => !ATTRIBUTES[a].adultOnly);
  const attr = pick(pool);
  const author = randomName();
  const timeline = Array.from({ length: randInt(2, 3) }, () =>
    makeForeignTweet(attr, author, adultMode, day - randInt(0, 3)),
  );
  return {
    id: uid("acct"),
    name: author.name,
    handle: author.handle,
    attribute: attr,
    isAdult: ATTRIBUTES[attr].adultOnly,
    bio: pick(BIO_BY_ATTR[attr]),
    followers: randInt(50, 50_000),
    timeline,
    followed: false,
  };
}

/**
 * 트윗 작성자(이름·핸들·계열)로부터 남의 계정 프로필을 합성한다.
 * bio·팔로워 수는 핸들 해시로 고정(같은 사람은 언제 봐도 같은 프로필). 프로필 페이지의 '게시물'
 * 탭을 채울 타임라인 트윗 몇 개를 그 계열로 생성한다(호출 시점 1회 — 저장돼 그동안은 안 흔들림).
 * 아무 남의 트윗이든 아바타를 눌러 프로필을 여는 용도(exploreSystem.accountForTweet가 호출).
 * 팔로우 여부(followed)는 systems가 상태로 덮는다.
 */
export function profileFromAuthor(
  name: string,
  handle: string,
  attribute: AttributeId,
  isAdult: boolean,
  day: number,
): Account {
  const h = hashInt(handle);
  const bios = BIO_BY_ATTR[attribute] ?? BIO_BY_ATTR.daily;
  const author = { name, handle };
  // 고정 캐릭터 계정이면 자기 bio·문구로 프로필을 채운다(공용 템플릿으로 말하면 캐릭터가 죽는다).
  const fixed = FIXED_AUTHORS[handle];
  const timeline = Array.from({ length: 3 }, (_, i) =>
    makeForeignTweet(attribute, author, isAdult, day - i, fixed?.lines),
  );
  return {
    id: "prof_" + handle,
    name,
    handle,
    attribute,
    isAdult,
    bio: fixed?.bio ?? bios[h % bios.length],
    followers: 50 + (h % 199_950), // 50 ~ 20만, 핸들로 고정
    timeline,
    followed: false,
  };
}

/** 특정 성향(카테고리)의 남 트윗 하나 생성(검색·카테고리 탭용) */
export function makeTweetOfAttribute(attr: AttributeId, adultMode: boolean, day: number): Tweet {
  return makeForeignTweet(attr, randomName(), adultMode, day);
}

