export interface AdultOfflineChoice {
  label: string;
  effect: EventEffect;
  /** 선택 결과 서사 */
  result: string;
  /** true면 그룹 플레이 해금 */
  unlockGroup?: boolean;
  /**
   * 이 선택으로 **찍혔다면** 그 출처. 며칠 뒤 협박 카톡으로 돌아온다(systems/blackmail).
   * ⚠️ result 본문에 촬영이 실제로 언급된 선택지에만 붙여라 — 안 그러면 "언제 찍혔지?"가 된다.
   */
  filmed?: BlackmailSource;
}

export interface AdultOfflineEncounter {
  id: AdultOfflineEncounterId;
  title: string;
  /** 조우 직후 선택 전 문구 */
  prompt: string;
  /** 힌트 한 줄 */
  hint: string;
  /** 이 활동들에서만 후보 */
  activities: readonly OfflineActivityId[];
  /** 최소 음란(0~999) — '얼마나 야한가'. 일반 관계 계열은 이것만 넘으면 뜬다. */
  minLewd: number;
  /**
   * 최소 변태력(0~999) — '어느 방향인가'. 강압·페티쉬 계열 전용 게이트.
   * 생략하면 `coercive: true`는 PERVERT_COERCIVE_MIN(systems/adultOffline)을, 일반 조우는 0을 쓴다.
   * 강압인데 특히 더 깊은 건(감금·집단 등) 여기서 개별로 올려라.
   */
  minPervert?: number;
  /** 심야 슬롯에서만 */
  lateOnly?: boolean;
  /** 비합의(강압/범죄) 상황 — '강압/범죄 안 보기'(adultNoCoercion) 켜면 후보에서 제외 */
  coercive?: boolean;
  /**
   * 이 조우가 성립하려면 필요한 처지. 없으면 누구에게나 뜬다.
   *
   * - `savanna`: 사바나 여캠을 하고 있어야 한다(`state.savannaJoined`).
   *   방송으로 얼굴·방 구조·생활 시간대가 이미 공개된 사람에게만 성립하는 소재라,
   *   일반 조우로 두면 "나를 어떻게 알고 찾아왔지?"가 설명되지 않는다.
   *
   * ⚠️ 새 값을 넣으면 `systems/adultOffline.meetsRequirement`에도 분기를 추가하라.
   *    안 하면 그 조우는 typecheck를 통과한 채 **영영 안 뜬다**.
   */
  requires?: "savanna";
  weight?: number;
  choices: AdultOfflineChoice[];
}

