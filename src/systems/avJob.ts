/**
 * 심야 AV 촬영을 처리한다.
 * 스탯 소모는 매회 적용되지만, 근무일(quota) 카운트는 하루 1회(lastWorkDay 가드)만 오른다.
 * @param acceptCondomless 노콘 제안을 승락했는지(이번 달 월급 +30만, 월 정산 시 리셋)
 * @returns 결과 서사 문구
 */
export function resolveAvWork(state: GameState, acceptCondomless: boolean): string {
  const job = state.avJob;
  if (!job) return "";
  state.resources.action = clampAction(state, state.resources.action - AV_WORK_ACTION_COST);
  gainSkill(state, "lewd", 12);
  state.resources.mental = clampMental(state, state.resources.mental - 8);
  state.resources.morality = clampResource(state.resources.morality - 4);

  // 근무일 카운트는 하루 1회만(스탯 효과는 매회)
  if (job.lastWorkDay !== state.day) {
    job.workDaysThisMonth += 1;
    job.totalWorkDays += 1; // 누적은 월 리셋을 안 탄다 — 직업 레벨 근거
    job.lastWorkDay = state.day;
    // 도전과제도 **같은 가드 안**에서 센다 — 밖으로 빼면 하루에 여러 번 찍혀 목표가 무의미해진다.
    recordMission(state, "shoot");
  }

  let narration = pick(AV_WORK_NARRATIONS);
  if (acceptCondomless) {
    job.condomlessThisMonth += 1;
    state.resources.morality = clampResource(state.resources.morality - 4);
    gainSkill(state, "lewd", 6);
    narration += AV_CONDOMLESS_NARRATION;
    // 노콘 촬영은 낮은 확률로 성병을 남긴다 → 회복까지 촬영 불가.
    if (Math.random() < AV_STD_CHANCE) {
      job.stdUntilDay = state.day + AV_STD_DAYS;
      state.resources.mental = clampMental(state, state.resources.mental - 8);
      narration += AV_STD_NARRATION;
      addSchedule(state, `성병 감염 — ${AV_STD_DAYS}일간 촬영 불가`, "system");
    }
  }

  addSchedule(state, "AV 심야 촬영", "offline");
  advanceTime(state, 1);
  return narration;
}
