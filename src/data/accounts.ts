/** 답글 작성자로 쓸 이름·성향(고정 계정 두 배열에서 찾는다). 괴담 계정은 성향이 없어 daily. */
function replyAuthorOf(handle: string): { name: string; attribute: AttributeId } | null {
  const ch = CHARACTER_AUTHORS.find((a) => a.handle === handle);
  if (ch) return { name: ch.name, attribute: ch.attribute };
  const ru = RUMOR_AUTHORS.find((a) => a.handle === handle);
  return ru ? { name: ru.name, attribute: "daily" } : null;
}

/** 이 트윗 문구에 귀속된 답글(TWEET_REPLIES에 없는 트윗이면 빈 배열). */
function groupReplies(text: string): TweetReply[] {
  return (TWEET_REPLIES[text] ?? []).flatMap((r) => {
    const who = replyAuthorOf(r.by);
    if (!who) return [];
    return [
      {
        id: uid("greply"),
        authorName: who.name,
        authorHandle: r.by,
        attribute: who.attribute,
        text: r.text,
        likes: randInt(0, 60),
      },
    ];
  });
}

/** 관찰일기 계정 핸들 — 날짜순 전용이라 랜덤 pick 풀에서 뺀다(위 DIARY 주석 참고). */
const DIARY_HANDLE = "daily_crush_log";

/** 캐릭터 고정 계정의 트윗 하나(피드에 낮은 확률로 섞인다). */
export function makeCharacterTweet(day: number): Tweet {
  const a = pick(CHARACTER_AUTHORS.filter((x) => x.handle !== DIARY_HANDLE));
  return makeForeignTweet(a.attribute, { name: a.name, handle: a.handle }, false, day, a.lines);
}

/**
 * 오늘 날짜의 관찰일기 트윗 한 개 — 1일차부터 문구 순서대로 하나씩.
 * 확률 판정이 없다(그 날짜엔 정확히 한 개). **문구를 다 쓰면 null** — 일기가 그날로 끝난 계정이라
 * 되돌아가 반복하지 않는다. 문구를 추가하면 그만큼 더 오래 쓴다.
 */
export function makeDiaryTweet(day: number): Tweet | null {
  const a = CHARACTER_AUTHORS.find((x) => x.handle === DIARY_HANDLE)!;
  const line = a.lines[Math.max(1, day) - 1];
  if (!line) return null;
  return makeForeignTweet(a.attribute, { name: a.name, handle: a.handle }, false, day, [line]);
}

/** 소문 트윗을 만든다(고정 패러디 핸들 + 오리지널 문구). 피드에 낮은 확률로 섞인다. */
export function makeRumorTweet(day: number): Tweet {
  const author = pick(RUMOR_AUTHORS);
  return {
    id: uid("rumor"),
    authorName: author.name,
    authorHandle: author.handle,
    attribute: "daily",
    isAdult: false,
    text: pick(author.lines),
    createdDay: day,
    likes: randInt(0, 500),
    retweets: randInt(0, 150),
    gainedFollowers: 0,
  };
}

/** 전용 문구 고정 계정(소문 8인 + 캐릭터 계정)이 피드에 뜰 확률 */
export const FIXED_AUTHOR_TWEET_CHANCE = 0.3;

/** 고정 계정 트윗이 떴을 때 소문 계정 쪽일 확률(나머지는 캐릭터 계정 — 기존 8:7 비율) */
const RUMOR_SHARE = 0.53;

/**
 * 확률적으로 전용 문구 고정 계정의 트윗을 하나 뽑는다(아니면 null).
 *
 * ⚠️ **한 판정에 한 번만 굴려야 한다.** 예전엔 `makeRandomTweet` 안에서만 굴렸는데,
 *    exploreTweets가 에코챔버 경로로 45%를 가로채면서 실제 노출이 선언값보다 낮아졌다.
 *    그래서 판정을 밖으로 꺼냈다 — 호출부는 이걸 **먼저** 부르고, null일 때만 나머지 경로로 간다.
 */
export function maybeFixedAuthorTweet(day: number): Tweet | null {
  if (!chance(FIXED_AUTHOR_TWEET_CHANCE)) return null;
  return chance(RUMOR_SHARE) ? makeRumorTweet(day) : makeCharacterTweet(day);
}

/** 고정 계정을 제외한 순수 랜덤 트윗(일반 유저 문구 풀). */
export function makeGenericTweet(adultMode: boolean, day: number): Tweet {
  const pool = adultMode
    ? ALL_ATTRIBUTE_IDS
    : ALL_ATTRIBUTE_IDS.filter((a) => !ATTRIBUTES[a].adultOnly);
  const attr = pick(pool);
  const author = randomName();
  return makeForeignTweet(attr, author, adultMode, day);
}

/** 신규 게시글 탐색용: 저자 계정 없이 트윗만 랜덤 생성(고정 계정 판정 포함) */
export function makeRandomTweet(adultMode: boolean, day: number): Tweet {
  return maybeFixedAuthorTweet(day) ?? makeGenericTweet(adultMode, day);
}
