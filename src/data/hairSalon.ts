/** 미니게임 최종 등급 */
export type HairGrade = "perfect" | "good" | "bad";

/** 대화 미니게임 한 문항 */
export interface HairQuestion {
  /** 미용사의 말 */
  ask: string;
  /** 선택지 — score가 높을수록 의도가 정확히 전달된다(0=애매, 1=무난, 2=정확) */
  options: { text: string; score: 0 | 1 | 2 }[];
}

