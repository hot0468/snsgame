/**
 * DM 대화 맥락. 상대가 방금 무슨 말을 했느냐에 따라 답장 풀이 달라진다.
 * - greet:    첫인사 오프닝에 대한 첫 답장
 * - photo:    성기 사진을 받은 직후
 * - offer:    티켓 양도·후원·크루/그룹방 초대·모텔 제안 등 '제안형' 스레드의 첫 답장
 * - meet:     상대가 오프라인 만남을 제안해두고 답을 기다리는 중
 * - followup: 이미 한 번 이상 답장한 뒤(인사 대신 대화를 이어간다)
 * 판정은 systems/dm.ts의 dmContext가 한다.
 */
export type DMContext = "greet" | "photo" | "offer" | "meet" | "followup";

/**
 * 내 답장 한 줄과, **그 문장에 대한** 상대의 대답 한 줄.
 *
 * ⚠️ 반드시 짝으로 붙어 있어야 한다. 예전엔 내 문장과 상대 문장을 각각 따로 뽑아서
 *    "다음엔 미리 물어봐주세요" → "더 보여드려도 돼요?" 처럼 대화가 어긋났다.
 *    새 대사를 추가할 때도 `partner`가 바로 위 `me`에 대한 대답인지 소리 내어 읽어보고 넣어라.
 */
