/** id로 화제를 찾는다. 없으면 undefined(구세이브·데이터 변경 대비). */
export function dmTopicById(id: string | undefined): DMTopic | undefined {
  return id ? DM_TOPICS.find((t) => t.id === id) : undefined;
}

/** DM_EXCHANGES에서 한쪽 문장만 뽑아낸 파생 뷰(단일 출처는 언제나 DM_EXCHANGES다). */
function sideOf(
  side: keyof DMExchange,
): Record<DMContext, Record<DMTone, string[]>> {
  const ctxs: DMContext[] = ["greet", "photo", "offer", "meet", "followup"];
  const tones: DMTone[] = ["friendly", "cool", "bold"];
  const out = {} as Record<DMContext, Record<DMTone, string[]>>;
  for (const c of ctxs) {
    out[c] = {} as Record<DMTone, string[]>;
    for (const t of tones) out[c][t] = DM_EXCHANGES[c][t].map((e) => e[side]);
  }
  return out;
}

/** 맥락별 내 답장 문장 목록(짝 정보 없이 문장만 필요할 때). */
export const REPLY_LINES_BY_CTX = sideOf("me");

/** 맥락별 상대 반응 문장 목록. 자유 입력 답장처럼 짝을 못 쓰는 경로가 쓴다. */
export const PARTNER_REPLIES_BY_CTX = sideOf("partner");

export function randomOpener(attr: AttributeId): string {
  const special = OPENERS_BY_ATTR[attr];
  const pool = special ? [...OPENERS, ...special] : OPENERS;
  return pool[Math.floor(Math.random() * pool.length)];
}
