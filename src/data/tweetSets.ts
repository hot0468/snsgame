const MENTION_BY_TEXT = new Map<string, string[]>();
for (const list of Object.values(TWEET_MENTION_SETS)) {
  for (const s of list) MENTION_BY_TEXT.set(s.text, s.mentions);
}

/** 특정 트윗 문구에 귀속된 멘션 3개(없으면 undefined) */
export function mentionsForText(text: string): string[] | undefined {
  return MENTION_BY_TEXT.get(text);
}

/** 카테고리·톤에 맞는 세트 트윗 문구들 */
export function setTextsFor(attr: AttributeId, tone: TweetTone): string[] {
  return TWEET_MENTION_SETS[attr].filter((s) => s.tone === tone).map((s) => s.text);
}

/** 카테고리의 모든 세트 트윗 문구(톤 무관) */
export function allSetTexts(attr: AttributeId): string[] {
  return TWEET_MENTION_SETS[attr].map((s) => s.text);
}
