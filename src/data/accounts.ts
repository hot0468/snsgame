/** 랜덤 유저 이름/핸들 생성(반응·계정 생성 등에서 공용으로 사용) */
export function randomName(): { name: string; handle: string } {
  const name = `${pick(NAME_PREFIX)}${pick(NAME_SUFFIX)}`;
  const handle = `${pick(["", "the_", "im_", "just_"])}${Math.random().toString(36).slice(2, 7)}`;
  return { name, handle };
}

