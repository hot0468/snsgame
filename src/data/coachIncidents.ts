/**
 * 배구부 코치 사건 — **도덕성이 낮을 때만** 터진다.
 *
 * 코치직은 남의 아이들과 남의 돈(훈련비·후원금)을 맡는 자리다. 그런데 지금까지는
 * 도덕성이 0이어도 아무 일이 없었다. 이 파일은 그 자리에 대가를 붙인다:
 *   도덕성이 낮으면 훈련 중 사건이 터지고 → 위로금을 물고 평판이 깎이며 →
 *   평판이 바닥나면 학교가 계약을 끊는다.
 *
 * 규칙(확률·효과 적용·해직 판정)은 `systems/coach.ts`가 소유한다. 여기는 '무엇을'만 선언한다.
 *
 * ⚠️ **학생은 피해자로만 등장한다.** 이 게임의 학교 소재 경계다(data/coachCamp.ts와 같은 규칙) —
 *    성인 소재를 섞지 마라. 여기서 벌어지는 일은 횡령·폭언·방치 같은 **지도자의 비위**다.
 */

export interface CoachIncident {
  id: string;
  /** 횡령(돈) / 트러블(아이들) */
  kind: "embezzle" | "trouble";
  title: string;
  text: string;
  /** 물어줘야 하는 위로금·변상금(원). 소지금이 모자라면 마이너스로 간다 */
  compensation: number;
  /** 평판 하락분(0~100 스케일) */
  reputationLoss: number;
  /** 정신력 변화(음수) */
  mentalDelta: number;
  /** 팀 완성도 하락분 — 아이들이 흔들리면 팀도 흔들린다 */
  teamStatLoss: number;
}

