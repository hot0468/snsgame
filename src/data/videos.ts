const VIEW_UNITS = ["만회", "천회"];
const AGE_LABELS = ["1일 전", "3일 전", "1주 전", "2주 전", "1개월 전", "어제"];

function randomViews(): string {
  const unit = pick(VIEW_UNITS);
  const n = unit === "만회" ? randInt(1, 480) : randInt(3, 99);
  return `조회수 ${n}${unit}`;
}

function hashHue(seed: string): number {
  let h = 0;
  for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
  return h % 360;
}

/** 기본 노출 카테고리(운동/스포츠는 운동 스탯이 붙으면 추가된다) */
export const DEFAULT_VIDEO_ATTRS: VideoAttribute[] = [
  "idol",
  "actor",
  "anime",
  "politics",
  "info",
  "animal",
  "humor",
  "gaming",
];

/** 영상을 무작위로 n개 생성한다. attrs로 노출 카테고리를 제한/추가할 수 있다. */
export function makeRandomVideos(n = 8, attrs: VideoAttribute[] = DEFAULT_VIDEO_ATTRS): Video[] {
  const out: Video[] = [];
  for (let i = 0; i < n; i++) {
    const attribute = pick(attrs);
    const tpl = pick(TEMPLATES[attribute]);
    const channel = pick(CHANNELS[attribute]);
    // 애니 영상은 특정 작품을 다룬다 — 제목에 작품명을 넣고, 시청 시 '봤던 작품'으로 기록된다.
    const work = attribute === "anime" ? pick(ANIME_WORKS) : null;
    const title = work ? `《${work.title}》 ${tpl.title}` : tpl.title;
    out.push({
      id: uid("vid"),
      title,
      channel,
      attribute,
      views: randomViews(),
      age: pick(AGE_LABELS),
      hue: hashHue(channel + title + i),
      tweetLines: [...tpl.tweetLines],
      workId: work?.id,
    });
  }
  // 같은 카테고리만 몰리지 않게 살짝 섞기
  return sample(out, out.length);
}
