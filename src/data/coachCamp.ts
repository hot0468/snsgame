/**
 * 성인 씬 하나. 상황(뒤풀이/전국체전/졸업생) × 강도 3단계로 고른다.
 *
 * 강도는 **뜨느냐가 아니라 어디까지 가느냐**다:
 *  - 문턱 없음: 가벼운 씬(성인 모드만 켜져 있으면 항상 여기까지는 온다)
 *  - `minLewd` 이상: 1:1(감독)
 *  - `minLewd` + `minPervert` 이상: 다인
 *
 * ⚠️ 배열은 **강도 내림차순**으로 놓는다(다인 → 1:1 → 가벼운 씬). 위에서부터 첫 매치를
 *    쓰므로 순서가 뒤집히면 가벼운 씬이 전부 가로채 다인 씬에 영영 도달하지 못한다.
 */
export interface CampAdultScene {
  id: string;
  title: string;
  /** 씬 본문 */
  text: string;
  /** 이 씬이 뜨는 최소 음란 */
  minLewd: number;
  /** 이 씬이 뜨는 최소 변태력(없으면 0) */
  minPervert?: number;
  /** 씬이 남기는 변화 */
  lewdGain: number;
  pervertGain: number;
  mentalDelta: number;
  moralityDelta: number;
}

