/** 카테고리에 어울리는 사진/영상 첨부를 하나 만든다(영상보다 사진이 흔함). */
export function makeMedia(attr: AttributeId): TweetMedia {
  const set = MEDIA_PROMPTS[attr];
  const kind = chance(0.7) ? "photo" : "video";
  const pool = kind === "photo" ? set.photo : set.video;
  return { kind, prompt: pick(pool) };
}
